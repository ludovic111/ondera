static MANIFESTS: LazyLock<Vec<Manifest>> = LazyLock::new(|| {
    native::manifests(&TABLES).expect("Stock plugin manifests are generated by the SDK")
});
fn index_of(name: &str) -> Option<usize> {
    MANIFESTS.iter().position(|m| m.name == name)
}
/// The vtable table, for tests of the ABI path.
pub fn tables() -> &'static [PluginVTable] {
    &TABLES
}
pub fn is_stock(name: &str) -> bool {
    INSTRUMENTS.contains(&name) || EFFECTS.contains(&name)
}
pub fn descriptor(name: &str) -> Option<Descriptor> {
    let instrument = INSTRUMENTS.contains(&name);
    if !instrument && !EFFECTS.contains(&name) {
        return None;
    }
    Some(Descriptor {
        id: format!("stock:{name}"),
        format: Format::Stock,
        name: name.into(),
        vendor: VENDOR.into(),
        path: String::new(),
        instrument,
        effect: !instrument,
        category: if instrument {
            "Instrument".into()
        } else {
            category(name).into()
        },
    })
}
pub fn descriptors() -> Vec<Descriptor> {
    INSTRUMENTS
        .iter()
        .chain(EFFECTS.iter())
        .filter_map(|n| descriptor(n))
        .collect()
}
pub fn params(name: &str) -> Vec<ParamInfo> {
    index_of(name).map_or_else(Vec::new, |i| native::param_infos(&MANIFESTS[i]))
}
/// Instantiate a stock plugin with every parameter at its default.
pub fn create(name: &str, rate: u32) -> Option<Instance> {
    let index = index_of(name)?;
    let descriptor = descriptor(name)?;
    if descriptor.instrument {
        native::instance_from(&TABLES_V2[index], &MANIFESTS[index], descriptor, rate).ok()
    } else {
        native::instance_from(&TABLES[index], &MANIFESTS[index], descriptor, rate).ok()
    }
}

