pub struct Chorus {
    rate: f64,
    delay: Delay,
    phase: f64,
    speed: f64,
    depth: f64,
    spread: f64,
    mix: f32,
}
impl Plugin for Chorus {
    const INFO: Info = Info::effect("org.ondera.stock.chorus", "Chorus", VENDOR, "Modulation")
        .describe("Two modulated delay taps with stereo spread.");
    fn params() -> Vec<ParamSpec> {
        vec![
            param("Rate", 0.05, 5.0, 0.6, "Hz"),
            param("Depth", 0.0, 100.0, 40.0, "%"),
            param("Spread", 0.0, 100.0, 50.0, "%"),
            param("Mix", 0.0, 100.0, 50.0, "%"),
        ]
    }
    fn new(rate: f64) -> Self {
        Self {
            rate,
            delay: Delay::new(0.06, rate as u32),
            phase: 0.0,
            speed: 0.6,
            depth: 0.4,
            spread: 0.5,
            mix: 0.5,
        }
    }
    fn set_param(&mut self, index: usize, value: f64) {
        match index {
            0 => self.speed = value,
            1 => self.depth = value / 100.0,
            2 => self.spread = value / 100.0,
            3 => self.mix = (value / 100.0) as f32,
            _ => {}
        }
    }
    fn reset(&mut self) {
        self.delay.clear();
    }
    fn process(&mut self, audio: &mut [[f32; 2]], _: &[NoteEvent], _: &ProcessContext) {
        let r = self.rate;
        for frame in audio {
            self.phase = (self.phase + self.speed / r).fract();
            let base = 0.016;
            let swing = 0.008 * self.depth;
            let l = self
                .delay
                .read((base + swing * (TAU * self.phase).sin()) * r);
            let ph = (self.phase + 0.5 * self.spread).fract();
            let rr = self.delay.read((base + swing * (TAU * ph).sin()) * r);
            self.delay.write(*frame);
            frame[0] += l[0] * self.mix;
            frame[1] += rr[1] * self.mix;
        }
    }
}

struct Comb {
    buffer: Vec<f32>,
    index: usize,
    store: f32,
}
impl Comb {
    fn new(len: usize) -> Self {
        Self {
            buffer: vec![0.0; len.max(1)],
            index: 0,
            store: 0.0,
        }
    }
    #[inline]
    fn process(&mut self, input: f32, feedback: f32, damp: f32) -> f32 {
        let out = self.buffer[self.index];
        self.store = out * (1.0 - damp) + self.store * damp;
        let next = input + self.store * feedback;
        self.buffer[self.index] = if next.is_finite() { next } else { 0.0 };
        self.index = (self.index + 1) % self.buffer.len();
        out
    }
}
struct Allpass {
    buffer: Vec<f32>,
    index: usize,
}
impl Allpass {
    fn new(len: usize) -> Self {
        Self {
            buffer: vec![0.0; len.max(1)],
            index: 0,
        }
    }
    #[inline]
    fn process(&mut self, input: f32) -> f32 {
        let buffered = self.buffer[self.index];
        let out = -input + buffered;
        self.buffer[self.index] = input + buffered * 0.5;
        self.index = (self.index + 1) % self.buffer.len();
        out
    }
}
/// A Freeverb-style reverb: eight combs and four allpasses per channel.
pub struct Space {
    combs: [Vec<Comb>; 2],
    allpasses: [Vec<Allpass>; 2],
    predelay: Delay,
    rate: f64,
    feedback: f32,
    damp: f32,
    pre: f64,
    width: f32,
    mix: f32,
}
impl Plugin for Space {
    const INFO: Info = Info::effect("org.ondera.stock.space", "Space", VENDOR, "Space & Time")
        .describe("Plate-style reverb with pre-delay, damping and width.");
    fn params() -> Vec<ParamSpec> {
        vec![
            param("Size", 0.0, 100.0, 55.0, "%"),
            param("Damp", 0.0, 100.0, 40.0, "%"),
            param("Pre-delay", 0.0, 100.0, 10.0, "ms"),
            param("Width", 0.0, 100.0, 100.0, "%"),
            param("Mix", 0.0, 100.0, 30.0, "%"),
        ]
    }
    fn new(rate: f64) -> Self {
        let scale = rate / 44100.0;
        let tune = |n: usize, offset: usize| ((n + offset) as f64 * scale) as usize;
        let combs = |offset| {
            [1116, 1188, 1277, 1356, 1422, 1491, 1557, 1617]
                .iter()
                .map(|&n| Comb::new(tune(n, offset)))
                .collect()
        };
        let allpasses = |offset| {
            [556, 441, 341, 225]
                .iter()
                .map(|&n| Allpass::new(tune(n, offset)))
                .collect()
        };
        Self {
            combs: [combs(0), combs(23)],
            allpasses: [allpasses(0), allpasses(23)],
            predelay: Delay::new(0.11, rate as u32),
            rate,
            feedback: 0.7 + 0.28 * 0.55,
            damp: 0.4 * 0.4,
            pre: 0.01,
            width: 1.0,
            mix: 0.3,
        }
    }
    fn set_param(&mut self, index: usize, value: f64) {
        match index {
            0 => self.feedback = (0.7 + 0.28 * value / 100.0) as f32,
            1 => self.damp = (0.4 * value / 100.0) as f32,
            2 => self.pre = value / 1000.0,
            3 => self.width = (value / 100.0) as f32,
            4 => self.mix = (value / 100.0) as f32,
            _ => {}
        }
    }
    fn reset(&mut self) {
        for c in self.combs.iter_mut().flatten() {
            c.buffer.fill(0.0);
            c.store = 0.0;
        }
        for a in self.allpasses.iter_mut().flatten() {
            a.buffer.fill(0.0);
        }
        self.predelay.clear();
    }
    fn process(&mut self, audio: &mut [[f32; 2]], _: &[NoteEvent], _: &ProcessContext) {
        let pre = self.pre * self.rate;
        let wet1 = self.mix * (self.width / 2.0 + 0.5);
        let wet2 = self.mix * ((1.0 - self.width) / 2.0);
        for frame in audio {
            let delayed = self.predelay.read(pre);
            self.predelay.write(*frame);
            let input = (delayed[0] + delayed[1]) * 0.015;
            let mut out = [0.0f32; 2];
            for (c, out_c) in out.iter_mut().enumerate() {
                let mut acc = 0.0;
                for comb in &mut self.combs[c] {
                    acc += comb.process(input, self.feedback, self.damp);
                }
                for ap in &mut self.allpasses[c] {
                    acc = ap.process(acc);
                }
                *out_c = acc;
            }
            frame[0] += out[0] * wet1 + out[1] * wet2;
            frame[1] += out[1] * wet1 + out[0] * wet2;
        }
    }
}

pub struct Echo {
    rate: f64,
    lines: [Delay; 2],
    sync: usize,
    time_ms: f64,
    feedback: f32,
    tone: f32,
    pingpong: bool,
    mix: f32,
    lp: [f32; 2],
    current: f64,
}
impl Echo {
    fn seconds(&self, tempo: f64) -> f64 {
        let beat = 60.0 / tempo.max(20.0);
        match self.sync {
            1 => beat / 4.0,
            2 => beat / 3.0,
            3 => beat / 2.0,
            4 => beat * 0.75,
            5 => beat,
            6 => beat * 1.5,
            7 => beat * 2.0,
            _ => self.time_ms / 1000.0,
        }
        .clamp(0.005, 2.0)
    }
}
impl Plugin for Echo {
    const INFO: Info = Info::effect("org.ondera.stock.echo", "Echo", VENDOR, "Space & Time")
        .describe("Tempo-synced stereo delay with ping-pong and tone.");
    fn params() -> Vec<ParamSpec> {
        vec![
            choice(
                "Sync",
                &["Free", "1/16", "1/8T", "1/8", "1/8.", "1/4", "1/4.", "1/2"],
                3,
            ),
            param("Time", 10.0, 2000.0, 375.0, "ms"),
            param("Feedback", 0.0, 95.0, 35.0, "%"),
            hz("Tone", 500.0, 20000.0, 6000.0),
            choice("Ping-pong", ON_OFF, 0),
            param("Mix", 0.0, 100.0, 35.0, "%"),
        ]
    }
    fn new(rate: f64) -> Self {
        Self {
            rate,
            lines: [Delay::new(2.1, rate as u32), Delay::new(2.1, rate as u32)],
            sync: 3,
            time_ms: 375.0,
            feedback: 0.35,
            tone: coef(rate, 1.0 / (TAU * 6000.0)),
            pingpong: false,
            mix: 0.35,
            lp: [0.0; 2],
            current: 0.0,
        }
    }
    fn set_param(&mut self, index: usize, value: f64) {
        match index {
            0 => self.sync = value.round().max(0.0) as usize,
            1 => self.time_ms = value,
            2 => self.feedback = (value / 100.0) as f32,
            3 => self.tone = coef(self.rate, 1.0 / (TAU * value.max(20.0))),
            4 => self.pingpong = value >= 0.5,
            5 => self.mix = (value / 100.0) as f32,
            _ => {}
        }
    }
    fn reset(&mut self) {
        self.lines.iter_mut().for_each(Delay::clear);
        self.lp = [0.0; 2];
    }
    fn process(&mut self, audio: &mut [[f32; 2]], _: &[NoteEvent], ctx: &ProcessContext) {
        let target = self.seconds(ctx.tempo) * self.rate;
        if self.current == 0.0 {
            self.current = target;
        }
        let glide = coef(self.rate, 0.05) as f64;
        for frame in audio {
            self.current += glide * (target - self.current);
            let l = self.lines[0].read(self.current)[0];
            let r = self.lines[1].read(self.current)[1];
            self.lp[0] += self.tone * (l - self.lp[0]);
            self.lp[1] += self.tone * (r - self.lp[1]);
            let (fl, fr) = (self.lp[0] * self.feedback, self.lp[1] * self.feedback);
            if self.pingpong {
                let mono = (frame[0] + frame[1]) * 0.5;
                self.lines[0].write([mono + fr, 0.0]);
                self.lines[1].write([0.0, fl]);
            } else {
                self.lines[0].write([frame[0] + fl, 0.0]);
                self.lines[1].write([0.0, frame[1] + fr]);
            }
            frame[0] += l * self.mix;
            frame[1] += r * self.mix;
        }
    }
}

pub struct Gate {
    rate: f64,
    threshold: f32,
    attack: f32,
    hold: u32,
    release: f32,
    range: f32,
    env: f32,
    gain: f32,
    held: u32,
}
impl Plugin for Gate {
    const INFO: Info = Info::effect("org.ondera.stock.gate", "Gate", VENDOR, "Dynamics")
        .describe("Noise gate with hold and range.");
    fn params() -> Vec<ParamSpec> {
        vec![
            param("Threshold", -80.0, 0.0, -40.0, "dB"),
            param("Attack", 0.1, 50.0, 1.0, "ms"),
            param("Hold", 0.0, 500.0, 50.0, "ms"),
            param("Release", 5.0, 1000.0, 100.0, "ms"),
            param("Range", -80.0, 0.0, -80.0, "dB"),
        ]
    }
    fn new(rate: f64) -> Self {
        Self {
            rate,
            threshold: db_to_gain(-40.0),
            attack: coef(rate, 0.001),
            hold: (rate * 0.05) as u32,
            release: coef(rate, 0.1),
            range: 0.0001,
            env: 0.0,
            gain: 0.0,
            held: 0,
        }
    }
    fn set_param(&mut self, index: usize, value: f64) {
        match index {
            0 => self.threshold = db_to_gain(value),
            1 => self.attack = coef(self.rate, value / 1000.0),
            2 => self.hold = (self.rate * value / 1000.0) as u32,
            3 => self.release = coef(self.rate, value / 1000.0),
            4 => self.range = db_to_gain(value),
            _ => {}
        }
    }
    fn reset(&mut self) {
        self.env = 0.0;
        self.gain = 0.0;
    }
    fn process(&mut self, audio: &mut [[f32; 2]], _: &[NoteEvent], _: &ProcessContext) {
        let follow = coef(self.rate, 0.0005);
        let decay = coef(self.rate, 0.02);
        for frame in audio {
            let peak = frame[0].abs().max(frame[1].abs());
            self.env += if peak > self.env { follow } else { decay } * (peak - self.env);
            let open = if self.env > self.threshold {
                self.held = self.hold;
                true
            } else if self.held > 0 {
                self.held -= 1;
                true
            } else {
                false
            };
            let target = if open { 1.0 } else { self.range };
            let c = if target > self.gain {
                self.attack
            } else {
                self.release
            };
            self.gain += c * (target - self.gain);
            frame[0] *= self.gain;
            frame[1] *= self.gain;
        }
    }
}

pub struct Limiter {
    rate: f64,
    input: f32,
    ceiling: f32,
    release: f32,
    delay: Delay,
    lookahead: usize,
    gain: f32,
}
impl Plugin for Limiter {
    const INFO: Info = Info::effect("org.ondera.stock.limiter", "Limiter", VENDOR, "Dynamics")
        .describe("Look-ahead brickwall limiter.");
    fn params() -> Vec<ParamSpec> {
        vec![
            param("Input", 0.0, 24.0, 0.0, "dB"),
            param("Ceiling", -20.0, 0.0, -0.3, "dB"),
            param("Release", 10.0, 1000.0, 80.0, "ms"),
        ]
    }
    fn new(rate: f64) -> Self {
        Self {
            rate,
            input: 1.0,
            ceiling: db_to_gain(-0.3),
            release: coef(rate, 0.08),
            delay: Delay::new(0.002, rate as u32),
            lookahead: (rate as u32 / 1000).max(1) as usize,
            gain: 1.0,
        }
    }
    fn set_param(&mut self, index: usize, value: f64) {
        match index {
            0 => self.input = db_to_gain(value),
            1 => self.ceiling = db_to_gain(value),
            2 => self.release = coef(self.rate, value / 1000.0),
            _ => {}
        }
    }
    fn reset(&mut self) {
        self.delay.clear();
        self.gain = 1.0;
    }
    fn latency(&self) -> u32 {
        self.lookahead as u32
    }
    fn process(&mut self, audio: &mut [[f32; 2]], _: &[NoteEvent], _: &ProcessContext) {
        for frame in audio {
            let x = [frame[0] * self.input, frame[1] * self.input];
            let peak = x[0].abs().max(x[1].abs());
            let needed = if peak > self.ceiling {
                self.ceiling / peak
            } else {
                1.0
            };
            if needed < self.gain {
                self.gain = needed;
            } else {
                self.gain += self.release * (needed - self.gain);
            }
            let delayed = self.delay.read(self.lookahead as f64);
            self.delay.write(x);
            frame[0] = (delayed[0] * self.gain).clamp(-self.ceiling, self.ceiling);
            frame[1] = (delayed[1] * self.gain).clamp(-self.ceiling, self.ceiling);
        }
    }
}

