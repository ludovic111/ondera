fn instrument_specs(preset: Preset) -> Vec<ParamSpec> {
    let d = InstrumentParams::for_preset(preset);
    let mut specs = vec![];
    match preset {
        Preset::Bass => {
            specs.push(hz("Cutoff", 60.0, 8000.0, d.cutoff));
            specs.push(param("Env Amount", 0.0, 100.0, d.env_amount * 100.0, "%"));
            specs.push(param("Decay", 5.0, 3000.0, d.decay * 1000.0, "ms"));
            specs.push(param("Sustain", 0.0, 100.0, d.sustain * 100.0, "%"));
            specs.push(param("Release", 10.0, 5000.0, d.release * 1000.0, "ms"));
        }
        Preset::Synth => {
            specs.push(choice("Wave", &["Saw", "Square", "Triangle"], 0));
            specs.push(hz("Cutoff", 100.0, 16000.0, d.cutoff));
            specs.push(param("Env Amount", 0.0, 100.0, d.env_amount * 100.0, "%"));
            specs.push(param("Attack", 1.0, 3000.0, d.attack * 1000.0, "ms"));
            specs.push(param("Decay", 5.0, 3000.0, d.decay * 1000.0, "ms"));
            specs.push(param("Sustain", 0.0, 100.0, d.sustain * 100.0, "%"));
            specs.push(param("Release", 10.0, 5000.0, d.release * 1000.0, "ms"));
        }
        Preset::Pad | Preset::Strings => {
            specs.push(hz("Cutoff", 100.0, 16000.0, d.cutoff));
            specs.push(param("Detune", 0.0, 50.0, d.detune, "ct"));
            specs.push(param("Attack", 1.0, 3000.0, d.attack * 1000.0, "ms"));
            specs.push(param("Release", 10.0, 5000.0, d.release * 1000.0, "ms"));
        }
        Preset::Drums => {}
        _ => {
            specs.push(param("Attack", 1.0, 3000.0, d.attack * 1000.0, "ms"));
            specs.push(param("Release", 10.0, 5000.0, d.release * 1000.0, "ms"));
        }
    }
    specs.push(param("Level", -24.0, 6.0, 0.0, "dB"));
    specs
}

const VOICES: usize = 32;
/// Pitch-bend range of the stock instruments, in semitones either way.
const BEND_SEMITONES: f64 = 2.0;
struct StockInstrument {
    preset: Preset,
    params: InstrumentParams,
    voices: [Option<Voice>; VOICES],
    /// Voices whose key is up while the sustain pedal (CC64) holds them.
    sustained: [bool; VOICES],
    pedal: bool,
    modulation: f64,
    pressure: f64,
    serial: u64,
    rate: f64,
    order: Vec<&'static str>,
}
impl StockInstrument {
    fn new(preset: Preset, rate: f64) -> Self {
        Self {
            preset,
            params: InstrumentParams::for_preset(preset),
            voices: [None; VOICES],
            sustained: [false; VOICES],
            pedal: false,
            modulation: 0.0,
            pressure: 0.0,
            serial: 0,
            rate,
            order: instrument_specs(preset).iter().map(|s| s.name).collect(),
        }
    }
    fn note_on(&mut self, pitch: u8, velocity: u8) {
        self.serial += 1;
        let voice = Voice::new(self.preset, pitch, velocity, self.serial);
        if let Some(slot) = self.voices.iter().position(|v| v.is_none()) {
            self.voices[slot] = Some(voice);
            self.sustained[slot] = false;
            return;
        }
        // Steal the oldest released voice, else the oldest voice.
        let victim = self
            .voices
            .iter()
            .enumerate()
            .filter_map(|(i, v)| v.map(|v| (i, v)))
            .min_by(|a, b| (a.1.held(), a.1.serial).cmp(&(b.1.held(), b.1.serial)))
            .map(|(i, _)| i)
            .unwrap_or(0);
        self.voices[victim] = Some(voice);
        self.sustained[victim] = false;
    }
    fn note_off(&mut self, pitch: u8) {
        let sustained = &self.sustained;
        if let Some((slot, _)) = self
            .voices
            .iter()
            .enumerate()
            .filter_map(|(i, v)| v.map(|v| (i, v)))
            .filter(|(i, v)| v.pitch == pitch && v.held() && !sustained[*i])
            .max_by_key(|(_, v)| v.serial)
        {
            if self.pedal {
                self.sustained[slot] = true;
            } else if let Some(v) = &mut self.voices[slot] {
                v.release();
            }
        }
    }
    fn set_pedal(&mut self, down: bool) {
        self.pedal = down;
        if !down {
            for (slot, voice) in self.voices.iter_mut().enumerate() {
                if std::mem::take(&mut self.sustained[slot]) {
                    if let Some(v) = voice {
                        v.release();
                    }
                }
            }
        }
    }
    /// Notes, sustain (CC64), mod wheel (CC1, vibrato), pressure (vibrato too), pitch bend
    /// (two semitones) and the channel-mode messages. Other controllers are ignored.
    fn apply(&mut self, e: Event) {
        match e.kind {
            event::NOTE_ON if e.value > 0 => self.note_on(e.key, e.value),
            event::NOTE_ON | event::NOTE_OFF => self.note_off(e.key),
            event::CONTROL => match e.key {
                1 => self.modulation = e.value.min(127) as f64 / 127.0,
                64 => self.set_pedal(e.value >= 64),
                120 => {
                    self.voices = [None; VOICES];
                    self.sustained = [false; VOICES];
                }
                121 => {
                    self.modulation = 0.0;
                    self.pressure = 0.0;
                    self.params.pitch_ratio = 1.0;
                    self.set_pedal(false);
                }
                123 => {
                    self.set_pedal(false);
                    for v in self.voices.iter_mut().flatten() {
                        v.release();
                    }
                }
                _ => {}
            },
            event::PITCH_BEND => {
                self.params.pitch_ratio = 2f64.powf(e.bend_amount() as f64 * BEND_SEMITONES / 12.0)
            }
            event::CHANNEL_PRESSURE => self.pressure = e.value.min(127) as f64 / 127.0,
            _ => {}
        }
        self.params.vibrato = self.modulation.max(self.pressure);
    }
    fn set(&mut self, index: usize, value: f64) {
        let Some(name) = self.order.get(index) else {
            return;
        };
        let p = &mut self.params;
        match *name {
            "Wave" => p.wave = value.round() as u8,
            "Cutoff" => p.cutoff = value,
            "Env Amount" => p.env_amount = value / 100.0,
            "Attack" => p.attack = value / 1000.0,
            "Decay" => p.decay = value / 1000.0,
            "Sustain" => p.sustain = value / 100.0,
            "Release" => p.release = value / 1000.0,
            "Detune" => p.detune = value,
            "Level" => p.level = db_to_gain(value),
            _ => {}
        }
    }
    fn reset(&mut self) {
        self.voices = [None; VOICES];
        self.sustained = [false; VOICES];
        self.pedal = false;
        self.modulation = 0.0;
        self.pressure = 0.0;
        self.params.pitch_ratio = 1.0;
        self.params.vibrato = 0.0;
    }
    /// Render with events and parameter changes applied at their frames. Both are sorted.
    fn process<E: Copy + Into<Event>>(
        &mut self,
        audio: &mut [[f32; 2]],
        events: &[E],
        params: &[TimedParam],
    ) {
        let (mut next, mut next_param) = (0, 0);
        for (i, frame) in audio.iter_mut().enumerate() {
            while let Some(change) = params.get(next_param).filter(|c| c.frame as usize <= i) {
                if change.value.is_finite() {
                    self.set(change.index as usize, change.value);
                }
                next_param += 1;
            }
            while let Some(event) = events
                .get(next)
                .map(|e| (*e).into())
                .filter(|e: &Event| e.frame as usize <= i)
            {
                self.apply(event);
                next += 1;
            }
            let mut sum = 0.0;
            for (slot, voice) in self.voices.iter_mut().enumerate() {
                if let Some(v) = voice {
                    sum += v.sample(&self.params, self.rate);
                    if v.finished(&self.params) {
                        *voice = None;
                        self.sustained[slot] = false;
                    }
                }
            }
            if !sum.is_finite() {
                sum = 0.0;
            }
            frame[0] += sum;
            frame[1] += sum;
        }
        // Anything scheduled at the block end.
        for change in &params[next_param..] {
            if change.value.is_finite() {
                self.set(change.index as usize, change.value);
            }
        }
        for event in &events[next..] {
            self.apply((*event).into());
        }
    }
}
macro_rules! instrument {
    ($ty:ident, $preset:expr, $id:literal, $name:literal, $doc:literal) => {
        pub struct $ty(StockInstrument);
        impl Plugin for $ty {
            const INFO: Info = Info::instrument($id, $name, VENDOR).describe($doc);
            fn params() -> Vec<ParamSpec> {
                instrument_specs($preset)
            }
            fn new(rate: f64) -> Self {
                Self(StockInstrument::new($preset, rate))
            }
            fn set_param(&mut self, index: usize, value: f64) {
                self.0.set(index, value)
            }
            fn reset(&mut self) {
                self.0.reset()
            }
            fn process(&mut self, audio: &mut [[f32; 2]], notes: &[NoteEvent], _: &ProcessContext) {
                self.0.process(audio, notes, &[])
            }
            fn process_events(
                &mut self,
                audio: &mut [[f32; 2]],
                events: &[Event],
                params: &[TimedParam],
                _: &ProcessContext,
            ) {
                self.0.process(audio, events, params)
            }
        }
    };
}
