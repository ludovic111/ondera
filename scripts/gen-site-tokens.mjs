// Emits site/tokens.css and site/tokens.js from the app's theme layer
// (frontend/src/theme), so the site wears the app's brand: the design-source
// theme, Skeuomorphic dark. The app ships several themes; the site wears one
// and only talks about the others (the theme gallery in site/index.html).
// Run from the repo root after `npm --prefix frontend ci`:
//   node scripts/gen-site-tokens.mjs
import { writeFileSync, mkdtempSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';
import { tmpdir } from 'node:os';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const require = createRequire(join(root, 'frontend/package.json'));
const esbuild = require('esbuild');

const out = join(mkdtempSync(join(tmpdir(), 'ondera-tokens-')), 'tokens.mjs');
await esbuild.build({
  entryPoints: [join(root, 'frontend/src/theme/tokens.ts')],
  bundle: true,
  format: 'esm',
  platform: 'node',
  outfile: out,
  logLevel: 'error',
});
const mod = await import(pathToFileURL(out).href);

// The one variant the site wears.
const THEME = 'skeuo';
const MODE = 'dark';
const SOURCE = 'frontend/src/theme';

const spec = mod.setTheme(THEME, MODE);
const [r, g, b] = spec.color.accent.match(/[\d.]+/g);
const vars = {
  ...mod.cssVariables(),
  // Two strengths of accent light for the page's own glows.
  '--site-accent-glow': `rgba(${r},${g},${b},0.07)`,
  '--site-accent-glow-strong': `rgba(${r},${g},${b},0.16)`,
  'color-scheme': MODE,
};

const css = [
  `/* GENERATED by scripts/gen-site-tokens.mjs from ${SOURCE} (${THEME} ${MODE}). Do not edit. */`,
  ':root {',
  ...Object.entries(vars).map(([k, v]) => `  ${k}: ${v};`),
  '}',
  '',
].join('\n');
writeFileSync(join(root, 'site/tokens.css'), css);

const tokens = JSON.parse(
  JSON.stringify({
    fontSize: mod.fontSize,
    size: mod.size,
    timeline: mod.timeline,
    color: spec.color,
    fill: spec.fill,
    line: spec.line,
    radius: spec.radius,
    canvasShadow: spec.canvasShadow,
    clipMix: spec.clipMix,
    font: { ui: spec.fontUi, mono: mod.font.mono },
  }),
);
const js = [
  `// GENERATED by scripts/gen-site-tokens.mjs from ${SOURCE} (${THEME} ${MODE}). Do not edit.`,
  '/** Tokens for the site\'s canvas code. */',
  `export const tokens = ${JSON.stringify(tokens, null, 2)};`,
  '',
].join('\n');
writeFileSync(join(root, 'site/tokens.js'), js);
console.log(`wrote ${Object.keys(vars).length} css vars for ${THEME} ${MODE}`);
