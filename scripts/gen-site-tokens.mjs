// Emits site/tokens.css and site/tokens.js from the app's theme layer
// (frontend/src/theme), so the site wears exactly what the window wears.
// Run from the repo root after `npm --prefix frontend ci`:
//   node scripts/gen-site-tokens.mjs
import { writeFileSync, mkdtempSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';
import { tmpdir } from 'node:os';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const require = createRequire(join(root, 'frontend/package.json'));
const esbuild = require('esbuild');

const out = join(mkdtempSync(join(tmpdir(), 'ondera-tokens-')), 'tokens.mjs');
await esbuild.build({
  entryPoints: [join(root, 'frontend/src/theme/tokens.ts')],
  bundle: true,
  format: 'esm',
  platform: 'node',
  outfile: out,
  logLevel: 'error',
});
const mod = await import(pathToFileURL(out).href);

const THEMES = ['modern', 'skeuo', 'aero'];
const MODES = ['dark', 'light'];
const SOURCE = 'frontend/src/theme';

// Properties that never change live on :root once. Every variant block then
// states every themed property, so a subtree can wear any theme under any page
// theme; theme-only properties a variant lacks are reset rather than inherited.
const glow = (accent, mode) => {
  const [r, g, b] = accent.match(/[\d.]+/g);
  const a = mode === 'dark' ? [0.07, 0.16] : [0.1, 0.2];
  return {
    '--site-accent-glow': `rgba(${r},${g},${b},${a[0]})`,
    '--site-accent-glow-strong': `rgba(${r},${g},${b},${a[1]})`,
  };
};
const block = (selector, vars) =>
  [`${selector} {`, ...Object.entries(vars).map(([k, v]) => `  ${k}: ${v};`), '}', ''];

const variants = [];
const themes = {};
for (const theme of THEMES)
  for (const mode of MODES) {
    const spec = mod.setTheme(theme, mode);
    variants.push({
      theme,
      mode,
      vars: { ...mod.cssVariables(), ...glow(spec.color.accent, mode), 'color-scheme': mode },
    });
    themes[`${theme}-${mode}`] = JSON.parse(
      JSON.stringify({
        color: spec.color,
        fill: spec.fill,
        line: spec.line,
        radius: spec.radius,
        canvasShadow: spec.canvasShadow,
        clipMix: spec.clipMix,
        font: { ui: spec.fontUi, mono: mod.font.mono },
      }),
    );
  }
const names = [...new Set(variants.flatMap((v) => Object.keys(v.vars)))];
const themed = names.filter((k) => new Set(variants.map((v) => v.vars[k])).size > 1);
const base = variants.find((v) => v.theme === 'skeuo' && v.mode === 'dark').vars;
const fixed = Object.fromEntries(Object.entries(base).filter(([k]) => !themed.includes(k)));
const pick = (vars) => Object.fromEntries(themed.map((k) => [k, vars[k] ?? 'initial']));

const css = [`/* GENERATED by scripts/gen-site-tokens.mjs from ${SOURCE}. Do not edit. */`];
// Without JavaScript the page wears the design-source theme.
css.push(...block(':root', { ...fixed, ...pick(base) }));
for (const v of variants)
  css.push(...block(`[data-theme="${v.theme}"][data-mode="${v.mode}"]`, pick(v.vars)));
writeFileSync(join(root, 'site/tokens.css'), css.join('\n'));

const js = [
  `// GENERATED by scripts/gen-site-tokens.mjs from ${SOURCE}. Do not edit.`,
  `const scales = ${JSON.stringify({ fontSize: mod.fontSize, size: mod.size, timeline: mod.timeline }, null, 2)};`,
  `export const themes = ${JSON.stringify(themes, null, 2)};`,
  '/** Live tokens for canvas code; setTheme() refills them in place. */',
  "export const tokens = { ...scales, ...structuredClone(themes['skeuo-dark']) };",
  'export function setTheme(theme, mode) {',
  "  Object.assign(tokens, structuredClone(themes[`${theme}-${mode}`] ?? themes['skeuo-dark']));",
  '}',
  '',
].join('\n');
writeFileSync(join(root, 'site/tokens.js'), js);
console.log(`wrote ${names.length} css vars (${themed.length} themed) × ${variants.length} variants`);
