const LIGHTS: Record<Mode, Light> = {
  dark: { hi: white, lo: black, glow: 1 },
  light: {
    // A white edge saturates on a pale face, so it starts high and rises slowly;
    // shade needs well under half the dark-theme alpha for the same depth.
    hi: (a) => white(Math.min(1, 0.55 + a * 1.4)),
    lo: (a) => umber(Number((a * 0.4).toFixed(3))),
    glow: 0.7,
  },
};

export function skeuo(mode: Mode): ThemeSpec {
  const dark = mode === "dark";
  const color = dark ? darkColor : lightColor;
  const fill = dark ? darkFill : lightFill;
  const line = dark ? darkLine : lightLine;
  const light = LIGHTS[mode];
  const gradient = physicalGradients(color);
  gradient.eqGrid = eqGrid(fill.eqGridLine, fill.eqZeroLine);
  const shadow = physicalShadows(color, light);
  if (!dark) {
    // Smoked glass swallows light: the wells keep the dark-theme recipe.
    shadow.wellDeep = `inset 0 2px 5px ${black(0.7)}, inset 0 0 0 1px ${black(0.55)}, 0 1px 0 ${white(0.85)}`;
    shadow.ledOff = `inset 0 1px 0 ${black(0.5)}`;
    shadow.clipSelected = `0 0 0 1.5px ${color.ink100}`;
    gradient.titleBar = `linear-gradient(180deg, ${al(0.9)}, ${al(0.855)})`;
    gradient.panelHeader = `linear-gradient(180deg, ${al(0.875)}, ${al(0.85)})`;
  }
  return {
    scheme: mode,
    color,
    gradient,
    shadow,
    fill,
    line,
    blur: { glass: "8px", glassAgent: "10px", glassCard: "12px" },
    radius: RADIUS,
    canvasShadow: physicalCanvasShadows(color, light),
    clipMix: dark
      ? { faceTop: 66, faceBottom: 50 }
      : { faceTop: 62, faceBottom: 78 },
    fontUi: FONT,
    capsTracking: "0.09em",
    vars: {
      "--display-glow": dark ? "0.2" : "0.16",
      "--ring-glow": dark ? alpha(color.accent, 0.55) : "transparent",
      // Brushed grain across the chassis: 1 px vertical striations, barely there.
      "--skeuo-grain": dark
        ? `repeating-linear-gradient(90deg, ${white(0.012)} 0 1px, transparent 1px 3px)`
        : `repeating-linear-gradient(90deg, ${alpha("#fff", 0.22)} 0 1px, transparent 1px 3px)`,
    },
  };
}
