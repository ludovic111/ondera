export function ink(mode: Mode): ThemeSpec {
  const dark = mode === "dark";
  const c = colors(mode);
  // `ink(a)` is the foreground at an alpha: rules, tints, ghosts.
  const tint = dark
    ? (a: number) => `rgba(240,236,226,${a})`
    : (a: number) => `rgba(28,26,20,${a})`;
  const solid = c.ink100;
  const paper = dark ? c.timeline : c.materialCard;
  const border = tint(dark ? 0.16 : 0.2);
  const borderStrong = tint(dark ? 0.34 : 0.55);
  const hairline = tint(dark ? 0.07 : 0.08);
  const ac = (a: number) => alpha(c.accent, a);
  const flat = (x: string) => `linear-gradient(${x}, ${x})`;
  /** A card laid on the page: hard offset, no blur. */
  const card = (d: number) =>
    `0 0 0 1px ${borderStrong}, ${d}px ${d}px 0 ${tint(dark ? 0.1 : 0.14)}`;

  const fill: Record<FillKey, string> = {
    glass: dark ? "rgba(30,29,26,.94)" : "rgba(252,250,245,.95)",
    glassAgent: dark ? "rgba(34,30,28,.95)" : "rgba(252,248,244,.96)",
    glassCard: dark ? "rgba(36,33,30,.96)" : "rgba(253,251,247,.97)",
    logLive: ac(dark ? 0.1 : 0.07),
    logChipLive: ac(dark ? 0.18 : 0.12),
    browserHighlight: tint(dark ? 0.08 : 0.07),
    cycleRuler: tint(dark ? 0.16 : 0.13),
    cycleLane: tint(dark ? 0.03 : 0.03),
    clipTitle: dark ? "rgba(0,0,0,.18)" : tint(0.06),
    rowShade: tint(dark ? 0.025 : 0.022),
    blackKeyRow: dark ? "rgba(0,0,0,.2)" : tint(0.045),
    eqGridLine: tint(0.06),
    eqZeroLine: tint(0.16),
    velocity: tint(dark ? 0.3 : 0.4),
    dragGhost: tint(0.1),
    pencilPreview: ac(0.25),
    cycleHandle: solid,
    dropTarget: ac(0.1),
    stepCell: tint(dark ? 0.06 : 0.05),
    hover: tint(dark ? 0.06 : 0.05),
    fadeShade: dark ? "rgba(0,0,0,.4)" : tint(0.16),
    fadeHandle: solid,
    markerFlag: alpha(paper, 0.94),
  };

  const line: Record<LineKey, string> = {
    barLine: tint(dark ? 0.1 : 0.13),
    beatLine: tint(dark ? 0.035 : 0.05),
    rulerBar: tint(dark ? 0.45 : 0.6),
    rulerTick: tint(dark ? 0.16 : 0.22),
    cycleEdge: solid,
    editorBar: tint(dark ? 0.11 : 0.14),
    editorBeat: tint(dark ? 0.04 : 0.055),
    waveform: tint(dark ? 0.82 : 0.8),
    waveformMid: tint(dark ? 0.3 : 0.3),
    midiNote: tint(dark ? 0.85 : 0.82),
    clipName: tint(dark ? 0.95 : 0.92),
    clipTitleBottom: tint(dark ? 0.12 : 0.16),
    clipHighlight: "transparent",
    clipContact: tint(dark ? 0.25 : 0.35),
    clipSelected: solid,
    cellDivider: hairline,
    dividerDark: border,
    laneTop: "transparent",
    laneBottom: tint(dark ? 0.09 : 0.1),
    rulerBottom: borderStrong,
    faderLine: tint(dark ? 0.5 : 0.6),
    faderLineHi: "transparent",
    milled: "transparent",
    milledHi: "transparent",
    dragGhostEdge: tint(0.6),
    noteSelected: c.accent,
    noteHighlight: "transparent",
    splitGuide: ac(0.95),
    staff: tint(0.4),
    noteHead: c.ink100,
    border,
    borderStrong,
    hairline,
    fadeCurve: tint(0.85),
    marker: c.accent,
    markerLane: ac(0.3),
  };

  const ring = `inset 0 0 0 1px ${border}`;
  const ringStrong = `inset 0 0 0 1px ${borderStrong}`;
  const none = "none";
  const rule = `inset 0 -1px 0 ${border}`;

  const shadow: Record<ShadowKey, string> = {
    raised: ring,
    raisedSm: ring,
    pressed: ringStrong,
    lit: none,
    knob: ringStrong,
    knobBig: ringStrong,
    knobInner: none,
    knobIndicator: none,
    faderCap: `0 0 0 1px ${solid}`,
    thumb: `0 0 0 1px ${solid}`,
    groove: none,
    grooveSoft: none,
    grooveShallow: ring,
    grooveSend: none,
    wellDeep: ringStrong,
    wellInput: ring,
    wellValue: none,
    segment: none,
    clip: none,
    clipAgent: `0 0 0 1.5px ${c.accent}`,
    clipSelected: `0 0 0 2px ${solid}`,
    ledLit: none,
    ledAccent: none,
    ledOff: none,
    ledEmpty: ring,
    glass: card(3),
    glassAgent: `0 0 0 1px ${c.accent}, 3px 3px 0 ${ac(0.25)}`,
    glassCard: `0 0 0 1px ${c.accent}, 4px 4px 0 ${ac(0.2)}`,
    accentDot: none,
    accentDotLg: none,
    accentBar: none,
    playhead: none,
    playheadRuler: none,
    headerCell: `inset -1px 0 0 ${border}, inset 0 -1px 0 ${hairline}`,
    headerCellAgent: `inset 3px 0 0 ${c.accent}, inset -1px 0 0 ${border}, inset 0 -1px 0 ${hairline}`,
    headerColumn: `inset -1px 0 0 ${border}`,
    colorStrip: none,
    swatch: `inset 0 0 0 1px ${border}`,
    swatchSm: none,
    trafficLight: `inset 0 0 0 1px ${border}`,
    // A printer's rule under the menu bar, and a double rule under the transport.
    titleBar: `inset 0 -1px 0 ${borderStrong}`,
    transport: `inset 0 -1px 0 ${borderStrong}, inset 0 -3px 0 ${c.transportTop}, inset 0 -4px 0 ${border}`,
    toolbar: rule,
    toolbarEditor: rule,
    rulerCorner: `inset -1px 0 0 ${border}, inset 0 -1px 0 ${borderStrong}`,
    panelLeft: `inset -1px 0 0 ${borderStrong}`,
    panelRight: `inset 1px 0 0 ${borderStrong}`,
    panelAgent: `inset 1px 0 0 ${borderStrong}`,
    panelAgentRail: `inset 1px 0 0 ${borderStrong}`,
    editorPane: `inset 0 1px 0 ${borderStrong}`,
    keyColumn: `inset -1px 0 0 ${borderStrong}`,
    keyRow: `inset 0 -1px 0 ${hairline}`,
    divider: rule,
    dividerTop: none,
    logEntry: ring,
    logChip: ring,
    insert: ring,
    insertEmpty: `inset 0 0 0 1px ${hairline}`,
    ledInsertOff: ring,
    window: `0 0 0 1px ${borderStrong}, 8px 8px 0 ${tint(0.12)}`,
    sendKey: none,
    menu: card(4),
    dialog: card(6),
    inlineInput: `0 0 0 1.5px ${solid}`,
    note: none,
    faderLineHi: none,
    milledHi: none,
    plate: ring,
    focus: `0 0 0 2px ${c.accent}`,
  };

  const gradient: Record<GradientKey, string> = {
    raised: flat(c.controlTop),
    raisedHover: flat(dark ? p(0.25) : p(0.94, 0.01)),
    pressed: flat(c.pressedTop),
    lit: flat(c.accent),
    transport: flat(c.transportTop),
    titleBar: flat(c.panel),
    segment: flat(c.segmentTop),
    thumb: flat(c.thumbTop),
    knob: flat(c.knobHi),
    knobBig: flat(c.knobBigHi),
    knobInner: "none",
    faderCap: flat(c.capTop),
    header: flat(c.headerTop),
    headerSelected: flat(c.headerSelectedTop),
    headerAgent: flat(c.headerAgentTop),
    panelHeader: flat(c.panel),
    insert: flat(c.insertTop),
    chip: flat(c.chipTop),
    sendKey: flat(c.accent),
    note: flat(c.noteTop),
    eqGrid: eqGrid(fill.eqGridLine, fill.eqZeroLine),
    dialog: flat(paper),
    dialogHeader: flat(paper),
    plate: flat(c.materialCard),
  };

  return {
    scheme: mode,
    color: c,
    gradient,
    shadow,
    fill,
    line,
    blur: { glass: "0px", glassAgent: "0px", glassCard: "0px" },
    radius: RADIUS,
    // E-paper redraws, it does not glide: very short, no overshoot anywhere.
    motion: {
      fast: "40ms",
      base: "90ms",
      slow: "140ms",
      ease: "cubic-bezier(0.4, 0, 0.2, 1)",
      enter: "cubic-bezier(0.2, 0, 0, 1)",
      exit: "cubic-bezier(0.4, 0, 1, 1)",
      settle: "cubic-bezier(0.2, 0, 0, 1)",
    },
    canvasShadow: NO_CANVAS_SHADOWS,
    // Track colour is a wash on the paper, not a fill.
    clipMix: dark
      ? { faceTop: 44, faceBottom: 44 }
      : { faceTop: 34, faceBottom: 34 },
    fontUi: FONT,
    capsTracking: "0.08em",
    vars: {
      "--display-glow": "0",
      "--ring-glow": "transparent",
      /** Type on an inverted (solid ink) surface. */
      "--ink-reverse": dark ? c.desk : c.materialCard,
      "--ink-solid": solid,
      "--ink-rule": borderStrong,
    },
  };
}
