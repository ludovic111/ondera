/**
 * Ink. Print and e-paper: one ink, one paper, one red pencil. No simulated light at
 * all: surfaces are the paper, structure is 1 px rules, and state is shown the way a
 * printer would, by inverting (a selected segment or an engaged switch is solid ink
 * with paper type). The only colour besides the track colours is vermilion, used for
 * the playhead, the agent and whatever is lit. Corners are square.
 *
 * Light is warm paper with near-black ink; dark is the same page inverted, paper-white
 * type on carbon, for a dim room. Nothing floats except menus and dialogs, and they
 * cast a hard offset shadow like a card laid on the page.
 */
