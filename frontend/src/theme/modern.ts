/**
 * Modern. No simulated light: depth comes from a five-step lightness ladder and
 * 1 px lines, never from gradients, glows or drop shadows on controls. One cool
 * neutral (oklch 264°, chroma ≤ 0.006) and one accent. Only things that float
 * above the window (menus, dialogs, the dragged fader cap) cast a shadow.
 *
 * Ladder, dark: canvas .165 · lane .185 · panel .205 · control .265 · active .33
 * Ladder, light: canvas .955 · panel .97 · lane .985 · control 1 · groove .935
 */
